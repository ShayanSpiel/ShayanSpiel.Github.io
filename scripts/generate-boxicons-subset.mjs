#!/usr/bin/env node
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = process.cwd();
const sourceRoot = join(root, "src");
const boxiconsCss = readFileSync(join(root, "node_modules/boxicons/css/boxicons.min.css"), "utf8");
const iconPattern = /\b(?:bx|bxl|bxs)-[a-z0-9-]+\b/g;
const icons = new Set();

function scan(dir) {
  for (const entry of readdirSync(dir)) {
    const file = join(dir, entry);
    if (relative(sourceRoot, file).startsWith("components/showcase/")) continue;
    if (statSync(file).isDirectory()) scan(file);
    else if (/\.(?:astro|mdx|ts|js)$/.test(file)) {
      for (const match of readFileSync(file, "utf8").matchAll(iconPattern)) icons.add(match[0]);
    }
  }
}
scan(sourceRoot);
icons.delete("bx-spin");

const rules = [...icons].sort().flatMap((icon) => {
  const escaped = icon.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const match = boxiconsCss.match(new RegExp(`\\.${escaped}:before\\{content:\"([^\"]+)\"\\}`));
  // Comments may mention invalid icon names while documenting a fallback.
  if (!match) return [];
  return [`.${icon}:before{content:"${match[1]}"}`];
});

const output = `/* Generated by scripts/generate-boxicons-subset.mjs. */
.bx{font-family:"boxicons"!important;font-weight:400;font-style:normal;font-variant:normal;line-height:1;display:inline-block;text-transform:none;speak:none;-webkit-font-smoothing:antialiased;-moz-osx-font-smoothing:grayscale}
@keyframes bx-spin{0%{transform:rotate(0)}100%{transform:rotate(359deg)}}
.bx-spin{animation:bx-spin 2s linear infinite}
${rules.join("\n")}
`;

const target = join(root, "src/styles/boxicons-subset.css");
writeFileSync(target, output);
console.log(`Wrote ${rules.length} Boxicons glyphs to ${relative(root, target)}.`);
